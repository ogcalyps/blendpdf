export interface ToolFaqItem {
  question: string;
  answer: string;
}

/**
 * Build the FAQ list for a tool page. Feeds both the visible `ToolFAQ`
 * accordion and the `FAQPage` structured data it emits, so the two can never
 * drift apart.
 */
export function useToolFaqs(namespace: string): ToolFaqItem[] {
  const t = useTranslations();

  return (TOOL_FAQ_KEYS[namespace] ?? [])
    .filter((slug) => t.has(`${namespace}.faq.${slug}.question`))
    .map((slug) => ({
      question: t(`${namespace}.faq.${slug}.question`),
      answer: t(`${namespace}.faq.${slug}.answer`),
    }));
}
